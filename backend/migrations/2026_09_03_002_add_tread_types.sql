-- «Протектор» — окреме поле поряд із «Типом підошви».
--
-- ЩО САМЕ РОЗДІЛЯЄМО (і чого свідомо НЕ розділяємо)
-- ─────────────────────────────────────────────────
-- «Тип підошви» роками вбирав відповіді на різні питання. Виміряно 03.09.2026
-- перехресною таблицею «вид товару × тип підошви»: у Кросівках 126 товарів
-- позначено «спортивна», а 127 — «плоска»/«платформа»/«танкетка». Тобто в межах
-- ОДНІЄЇ категорії половина людей відповідала про одне, половина — про інше.
--
-- Повної дихотомії (профіль ↔ протектор) власник робити не став — і це
-- свідоме рішення, а не недогляд. Виноситься лише те, що однозначно описує
-- ПОВЕРХНЮ контакту: гладка, рифлена, рельєфна, тракторна.
--
-- «спортивна» (137 товарів) НЕ переїжджає сюди й лишається як є. Вона й не є
-- властивістю протектора: 82% таких товарів уже мають Стиль «Спортивний» /
-- «Трекінговий» / «Біговий», тобто поле дублює наявне. А те, що в «спортивній
-- підошві» справді про підошву — матеріал — має власне місце в
-- product_materials (position='sole'), заповнене на 423 товарах.
--
-- ЧОМУ «тракторна» ТУТ, ХОЧ ВОНА Й ПРО КОНСТРУКЦІЮ ТЕЖ
-- ────────────────────────────────────────────────────
-- Тракторна підошва справді описує і глибокі шашки, і масивність. Складені
-- поняття такого штибу існують САМЕ ТОМУ, що поле одне: людина змушена обрати
-- одне слово на все, що бачить. Маючи два поля, той самий чобіт описується
-- парою «профіль = платформа, протектор = тракторна», і жоден факт не втрачено.
-- Дані підтверджують, що це реальна властивість підошви, а не тінь виду чи
-- стилю: 25 із 32 «тракторних» — це Туфлі, а по стилях вони розкидані від
-- Класичного до Елегантного.

CREATE TABLE IF NOT EXISTS tread_types (
    id            SERIAL PRIMARY KEY,
    treadtypename VARCHAR(100) UNIQUE NOT NULL,
    created_at    TIMESTAMP DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_tread_types_treadtypename ON tread_types (treadtypename);

ALTER TABLE IF EXISTS products
    ADD COLUMN IF NOT EXISTS treadtypeid INTEGER
    REFERENCES tread_types(id) ON DELETE SET NULL;

-- Канон — з малої літери, як у решті описових довідників (sole_types,
-- toe_shapes): резолвер приводить першу літеру вниз перед INSERT, і різний
-- регістр інакше плодив би дублікати.
INSERT INTO tread_types (treadtypename) VALUES
    ('гладка'),
    ('рифлена'),
    ('рельєфна'),
    ('тракторна')
ON CONFLICT (treadtypename) DO NOTHING;

COMMENT ON COLUMN products.treadtypeid IS
    'Протектор — поверхня контакту підошви. Профіль (плоска/платформа/танкетка) лишається в soletypeid.';
