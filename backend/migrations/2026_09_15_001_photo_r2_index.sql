-- Індекс фото в R2 — знімок «що є в хмарі», який BMS оновлює при кожній
-- перебудові свого R2-індексу.
--
-- НАВІЩО ТАБЛИЦЯ, ЯКЩО Є САМ R2. Синхрон каталогу (BMS_catalog/cloud/
-- sync_to_cloud.py) наповнював хмарну `catalog_images` СКАНУВАННЯМ ЛОКАЛЬНОГО
-- ДИСКА — тобто після втрати теки вітрина втратила б усі фото, хоча файли в R2
-- живі. Синхрон уже читає bsstorage; давати йому ще й ключі R2 та boto3
-- означало б дублювати секрети. Тому індекс кладе сюди BMS, а синхрон читає.
--
-- Джерело правди — R2; ця таблиця похідна і перезаписується цілком.
CREATE TABLE IF NOT EXISTS photo_r2_index (
    relpath    TEXT PRIMARY KEY,      -- «<категорія>/<файл>.webp», як у міорі й у R2
    version    TEXT,                  -- ETag обʼєкта — для ?v= у каталозі
    indexed_at TIMESTAMP NOT NULL DEFAULT now()
);
