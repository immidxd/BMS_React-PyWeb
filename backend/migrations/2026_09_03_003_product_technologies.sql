-- Технології стають many-to-many, як матеріали.
--
-- ЩО ВИМІРЯНО (03.09.2026)
-- ────────────────────────
-- У довіднику 93 значення, з них 39 (41%) — складені: «Vibram, MEGAGRIP,
-- Gore-tex», а рекордсмен містить сім технологій в одній комірці. Розібравши
-- їх, дістаємо 82 АТОМАРНІ технології.
--
-- ⚠️ Чесно про виграш: 93 → 82 — це лише 12%, і поле заповнене на 1.4% товарів
-- (173 з 12177). Тобто негайна користь помірна. Справжня причина не в
-- сьогоднішньому безладі, а в тому, що з одним FK кожна НОВА комбінація
-- породжує новий рядок довідника: додав товар із Vibram+Gore-Tex+X — і в
-- таблиці 94-те значення, яке більше ніколи не повториться. Зростання
-- комбінаторне й нескінченне. Many-to-many це зупиняє: три атоми
-- переюзуються, нових рядків нуль.
--
-- ЧОМУ НОВОЇ КОЛОНКИ В ЖУРНАЛІ НЕ ТРЕБА
-- ─────────────────────────────────────
-- Колонка «Технології» вже містить списки через кому — рівно те, що ми й
-- зберігатимемо. Змінюється лише те, як ми їх читаємо й пишемо, а не аркуш.
-- Тому цей крок, на відміну від переносу протектора, не потребує ані правки
-- 431 вкладки, ані перезапуску застосунку заради воркера черги.
--
-- РОЗДІЛЮВАЧІ
-- ───────────
-- Реально трапляються два: кома і крапка з пробілом. Пара
-- «gore-tex, Meta-Rocker» / «gore-tex. Meta-Rocker» — це одне й те саме,
-- розведене по двох рядках довідника лише через друкарську крапку.
--
-- Скалярний products.technologyid НАВМИСНО лишається на місці цією міграцією:
-- заповнення таблиці робиться окремим скриптом, і поки код читає старе поле,
-- база мусить лишатись робочою. Прибирання скаляра — окреме рішення, бо воно
-- зачіпає writeback-мапу й потребує синтетичного поля, як у матеріалів.

CREATE TABLE IF NOT EXISTS product_technologies (
    product_id    INTEGER NOT NULL REFERENCES products(id)     ON DELETE CASCADE,
    technology_id INTEGER NOT NULL REFERENCES technologies(id) ON DELETE CASCADE,
    -- Порядок у комірці аркуша: «Vibram, MEGAGRIP» ≠ «MEGAGRIP, Vibram» для ока
    -- власника, тож зберігаємо той, у якому записано.
    ord           INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (product_id, technology_id)
);

CREATE INDEX IF NOT EXISTS ix_product_technologies_product
    ON product_technologies (product_id);
CREATE INDEX IF NOT EXISTS ix_product_technologies_technology
    ON product_technologies (technology_id);

COMMENT ON TABLE product_technologies IS
    'Технології товару (many-to-many). ord — порядок у комірці «Технології» Журналу.';
