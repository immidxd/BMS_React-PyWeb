-- Приховані знімки: фото лишається на диску й у R2, але ніде не пропонується.
--
-- ЧОМУ ОКРЕМА ТАБЛИЦЯ, А НЕ ЧЕТВЕРТИЙ ВИД І НЕ ПЕРЕЙМЕНУВАННЯ.
--   • Вид (official/real/defect) закодований в імені файлу. «Сховано» до нього
--     ортогональне: сховати можна знімок будь-якого виду, і при поверненні
--     треба знати, куди саме його вернути. Четвертий вид цю пам'ять стер би.
--   • Перейменування здавалось дешевшим (є готовий move_one_photo), але в
--     каталозі `_classify` має ЗАПАСНИЙ варіант «official»: усе, що не `_defN`
--     і не `_00N`, вважається студійним. Перейменований файл не сховався б, а
--     навпаки лишився б публічним — гірше, ніж було.
--
-- Ключ — НОМЕР товару, а не products.id: фото належать номеру, спільні для всієї
-- ростовки, і переживають видалення окремого рядка. Номер зберігаємо
-- нормалізованим (без '#', без пробілів) — саме в такому вигляді з ним працює
-- product_images._normalize_number.
CREATE TABLE IF NOT EXISTS product_photo_hidden (
    id            SERIAL PRIMARY KEY,
    productnumber VARCHAR(64)  NOT NULL,
    filename      VARCHAR(255) NOT NULL,
    hidden_at     TIMESTAMP    NOT NULL DEFAULT now(),
    hidden_by     VARCHAR(64)
);

-- Один запис на файл. Повторне приховування — не помилка, а no-op.
-- ⚠️ COLLATE "und-x-icu" обов'язковий: база створена з локаллю C, де lower()
-- НЕ опускає кирилицю ('Ф4384' лишається 'Ф4384'). Без ICU індекс вважав би
-- 'Ф4384' і 'ф4384' різними ключами.
CREATE UNIQUE INDEX IF NOT EXISTS ux_photo_hidden
    ON product_photo_hidden (lower(productnumber COLLATE "und-x-icu"),
                             lower(filename COLLATE "und-x-icu"));
