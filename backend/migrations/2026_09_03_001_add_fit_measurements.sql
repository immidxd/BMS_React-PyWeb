-- Два заміри посадки, яких бракувало: ширина устілки й обхват халяви.
--
-- ЧОМУ ШИРИНА УСТІЛКИ В СМ, КОЛИ Є `width`
-- ────────────────────────────────────────
-- `width` — буквена оцінка (вузька / стандартна / широка). Виміряно 03.09.2026
-- на 9309 одиницях взуття:
--     довжина устілки в см (`measurementscm`) — заповнена на 93.9%
--     ширина буквою        (`width`)          — заповнена на  0.8%
-- Це не лінь. Заповнюється те, що МІРЯЄТЬСЯ, і не заповнюється те, що
-- ОЦІНЮЄТЬСЯ: приклав лінійку — записав число, а «широка відносно чого» —
-- судження, яке роками пропускають. Тож ширина в сантиметрах з високою
-- ймовірністю справді заповнюватиметься, на відміну від буквеної.
-- Буквену НЕ чіпаємо: вона є в Журналі й нікому не заважає.
--
-- ЧОМУ ОБХВАТ ХАЛЯВИ
-- ──────────────────
-- 2361 товар високого взуття (чоботи, ботинки, напівсапоги, берці) — і в
-- ЖОДНОГО не заповнено ані висоти халяви, ані обхвату. Висота в схемі була й
-- стояла порожня; обхвату не існувало взагалі. Для чобота це головний вимір
-- посадки після розміру: людина з широкою литкою не взує чобіт незалежно від
-- розміру ноги, і саме це найчастіше питають у переписці.
--
-- ЧОМУ MIN/MAX, А НЕ ОДНЕ ЧИСЛО
-- ─────────────────────────────
-- Так уже влаштовані всі інші заміри, і для халяви це не формальність:
-- халява, що розширюється догори, чесно описується як «від 32 до 38», а одне
-- число тут ввело б в оману половину покупців. Для решти замірів min = max.
--
-- ⚠️ ОБХВАТ — ПОВНИЙ, НЕ НАПІВОБХВАТ. Заміри одягу поруч (`pog`, `pob`, `pot`)
-- зберігають ПОЛОВИНУ обхвату, і рука сама тягнеться поділити навпіл. Тут —
-- повне коло стрічки навколо халяви. Підказка в картці має це проговорювати.
--
-- Колонки Журналу «Ширина устілки» і «Обхват халяви» вставлені ДО цієї
-- міграції — свідомо. Зайва колонка, якої код не знає, нешкідлива; зворотний
-- порядок дав би writeback "missing in sheet", а цей рядок у
-- journal_sync._PERMANENT_MARKERS: задача стала б 'skipped' без повтору й без
-- видимої помилки, і аркуш розійшовся б із базою непомітно.

ALTER TABLE IF EXISTS products
    ADD COLUMN IF NOT EXISTS measurements_insole_width_min DOUBLE PRECISION;
ALTER TABLE IF EXISTS products
    ADD COLUMN IF NOT EXISTS measurements_insole_width_max DOUBLE PRECISION;

ALTER TABLE IF EXISTS products
    ADD COLUMN IF NOT EXISTS measurements_shaft_circumference_min DOUBLE PRECISION;
ALTER TABLE IF EXISTS products
    ADD COLUMN IF NOT EXISTS measurements_shaft_circumference_max DOUBLE PRECISION;

COMMENT ON COLUMN products.measurements_insole_width_min IS
    'Ширина устілки, см — у найширшому місці (зона пучків). Знімну устілку вийняти.';
COMMENT ON COLUMN products.measurements_shaft_circumference_min IS
    'Обхват халяви, см — ПОВНЕ коло у найширшому місці, чобіт застебнутий. Не напівобхват.';
