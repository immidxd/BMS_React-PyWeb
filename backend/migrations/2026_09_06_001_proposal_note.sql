-- Якір перевірки для текстових пропозицій.
--
-- Причина конкретна. 06.09.2026 модель gemini-3.5-flash, дивлячись на чітке фото
-- бирки Adidas із написом «JQ8356», запропонувала артикул «HQ8708». Не
-- відмовилась, не помилилась у символі — ВИГАДАЛА правдоподібний код.
--
-- Для полів із закритим переліком такого статись не може: там enum, і значення
-- поза списком фізично не пройде. Текстові поля (артикул, бренд, модель) цього
-- захисту не мають за визначенням — їх читають, а не обирають.
--
-- Тому для них потрібен якір: модель зобовʼязана процитувати рядок, У ЯКОМУ
-- вона це побачила. Вигадка такого контексту не має, а людині досить глянути,
-- щоб порівняти з фото.
ALTER TABLE IF EXISTS product_field_proposals
    ADD COLUMN IF NOT EXISTS note TEXT;

COMMENT ON COLUMN product_field_proposals.note IS
    'Якір перевірки: дослівний контекст, у якому модель побачила значення. Для текстових полів обовʼязковий.';
