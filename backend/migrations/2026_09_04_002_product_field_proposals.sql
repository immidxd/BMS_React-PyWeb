-- Пропозиції автозаповнення: те, що модель РОЗПІЗНАЛА, але ще ніхто не прийняв.
--
-- ЧОМУ ОКРЕМА ТАБЛИЦЯ, А НЕ ПОЛЕ В products
-- ─────────────────────────────────────────
-- Пропозиція — не правка. Щойно значення потрапляє в products, воно тягне за
-- собою лок (`manually_edited_fields`) і задачу в `journal_writeback_queue`,
-- тобто їде в живий аркуш власника. Саме цього тут не має статись: модель не
-- має права запису взагалі. У картку значення потрапляє ЛИШЕ після
-- підтвердження людиною і ЛИШЕ через звичайний update_product — той самий код,
-- яким працює ручне введення. Тому нового шляху запису не існує, а лок, черга
-- й реконсиляція з Журналом навіть не знають, що хтось щось пропонував.
--
-- ЧОМУ ЗБЕРІГАЄМО НАЗВУ, А НЕ FK
-- ──────────────────────────────
-- `value` — це назва («тракторна»), а не id. Пропозиція існує ДО резолву, і
-- резолвиться вона в момент прийняття, тим самим `_resolve_lookup_id_by_name`,
-- що й ручне введення — з канонізацією перевірених варіантів і в строгому
-- режимі (без CREATE). Якби ми зберігали id, то мусили б резолвити на вході, і
-- третій рубіж (поріг певності) вже не мав би що відкинути.
--
-- ЧОМУ ОДНА ВІДКРИТА ПРОПОЗИЦІЯ НА ПОЛЕ
-- ─────────────────────────────────────
-- Повторне розпізнавання того самого товару має ЗАМІНЮВАТИ невирішену
-- пропозицію, а не накопичувати їх: інакше в картці зʼявиться черга з трьох
-- варіантів «тип підошви», і людина муситиме розбиратись, який свіжіший.
-- Частковий унікальний індекс нижче — те саме рішення, що в
-- journal_writeback_queue для пари (product_id, field).
--
-- СТАН `stale`
-- ───────────
-- Поле могли заповнити руками або парсером, поки пропозиція чекала. Тоді вона
-- більше не актуальна, але й не «відхилена» — людина її не бачила. Різниця
-- важлива для майбутньої статистики якості: відхилення це сигнал про модель,
-- а stale — ні.

CREATE TABLE IF NOT EXISTS product_field_proposals (
    id            BIGSERIAL PRIMARY KEY,
    product_id    INTEGER      NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    -- Ім'я поля В ТОМУ ВИГЛЯДІ, у якому його приймає ProductUpdate
    -- («sole_type_name», «technology_name»): тоді прийняття — це просто виклик
    -- update_product без жодного перекладу імен.
    field         VARCHAR(64)  NOT NULL,
    value         TEXT,
    -- 0..1. Нижче порога пропозиція взагалі не створюється — але поріг живе в
    -- коді, а не тут: його підбирають виміром, і він різний для різних полів.
    confidence    NUMERIC(4,3),
    status        VARCHAR(16)  NOT NULL DEFAULT 'pending',
    -- Звідки: 'photo' + модель. Потрібно, щоб порівнювати провайдерів на
    -- реальних прийняттях, а не лише на лабораторній вибірці.
    source        VARCHAR(32)  NOT NULL DEFAULT 'photo',
    model         VARCHAR(64),
    -- Імена файлів, на яких це побачено, через кому. Дає перевірити очима, чому
    -- модель так вирішила, — без цього розбір помилки перетворюється на здогад.
    source_photos TEXT,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    decided_at    TIMESTAMPTZ,
    CONSTRAINT product_field_proposals_status
        CHECK (status IN ('pending', 'accepted', 'rejected', 'stale'))
);

-- Одна ВІДКРИТА пропозиція на поле; вирішені лишаються історією.
CREATE UNIQUE INDEX IF NOT EXISTS uq_product_field_proposals_open
    ON product_field_proposals (product_id, field) WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS ix_product_field_proposals_pending
    ON product_field_proposals (product_id) WHERE status = 'pending';

COMMENT ON TABLE product_field_proposals IS
    'Пропозиції автозаповнення з фото. НЕ правка: у products потрапляють лише через update_product після підтвердження людиною.';
