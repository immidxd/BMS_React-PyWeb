-- Облік витрат на AI-виклики й жорстка місячна стеля.
--
-- ЧОМУ ЦЕ ТАБЛИЦЯ, А НЕ ЛІЧИЛЬНИК У ПАМʼЯТІ
-- ─────────────────────────────────────────
-- Стеля має пережити перезапуск застосунку — інакше кожен рестарт обнуляв би
-- витрачене, і межа існувала б лише на папері. Плюс без порядкового обліку
-- неможливо відповісти на питання «куди пішли гроші»: скільки коштувало
-- дозаповнення старого проти нових товарів, яка модель дорожча на практиці.
--
-- ЧОМУ ЗАПИСУЄМО НАВІТЬ НЕВДАЛІ ВИКЛИКИ
-- ─────────────────────────────────────
-- Провайдер тарифікує вхідні токени навіть тоді, коли відповідь не склалась
-- (обрив, фільтр, таймаут після відправки). Рахувати лише успішні означало б
-- систематично занижувати витрачене — саме та помилка, через яку стеля
-- «раптом» виявляється перевищеною.
--
-- ЧОМУ ВАРТІСТЬ ЗБЕРІГАЄМО, А НЕ РАХУЄМО НА ЛЬОТУ
-- ───────────────────────────────────────────────
-- Ціни провайдерів змінюються. Перерахунок історії за сьогоднішнім прайсом
-- показував би не те, що ми справді заплатили. Тариф, за яким порахували,
-- фіксується разом із рядком.

CREATE TABLE IF NOT EXISTS ai_spend_log (
    id             BIGSERIAL PRIMARY KEY,
    provider       VARCHAR(32)  NOT NULL DEFAULT 'gemini',
    model          VARCHAR(64)  NOT NULL,
    -- Навіщо викликали: 'autofill' (новий товар), 'backfill' (стара база),
    -- 'eval' (вимір). Без цього неможливо окремо обмежити дозаповнення, яке
    -- одне здатне зʼїсти місячну стелю за годину.
    purpose        VARCHAR(24)  NOT NULL DEFAULT 'autofill',
    product_id     INTEGER,
    prompt_tokens  INTEGER      NOT NULL DEFAULT 0,
    output_tokens  INTEGER      NOT NULL DEFAULT 0,
    -- Тариф на момент виклику, $/1M токенів — щоб історія лишалась відтворюваною.
    rate_in_usd    NUMERIC(10,4),
    rate_out_usd   NUMERIC(10,4),
    cost_usd       NUMERIC(12,6) NOT NULL DEFAULT 0,
    ok             BOOLEAN      NOT NULL DEFAULT TRUE,
    error          TEXT,
    called_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Основний запит гальма: сума за поточний місяць. Індекс саме під нього.
CREATE INDEX IF NOT EXISTS ix_ai_spend_log_month
    ON ai_spend_log (called_at);
CREATE INDEX IF NOT EXISTS ix_ai_spend_log_purpose
    ON ai_spend_log (purpose, called_at);

COMMENT ON TABLE ai_spend_log IS
    'Витрати на AI-виклики. Гальмо читає суму за поточний місяць і ВІДМОВЛЯЄ у виклику за межею.';
