"""Канонізація статі товару — ЄДИНЕ джерело правди.

Статей рівно ТРИ: «Жіноча», «Чоловіча», «Унісекс» (плюс службова «Невідомо»
id=0, що НЕ показується у фільтрах). Будь-який ввід із журналу/форми/картки —
з різними закінченнями («Жіночі», «Жіноче», «жіночий»), регістром чи однина/
множина — мусить звестись до однієї з трьох канонічних назв або до '' (пропуск).

⚠️ Чому так: різні закінчення створювали ДУБЛІ статей у таблиці `genders`
(«Жіночі» поряд із «Жіноча» тощо) → у фільтрі дублювались чипи. Тепер усі шляхи
резолву (парсер products+workspace, add-product, edit-картка) проходять через цю
функцію, а резолвери НІКОЛИ не створюють не-канонічну стать (нормалізована
назва завжди вже існує в БД). Дзеркалить prefix-логіку фронту `genderKind`.
"""

from __future__ import annotations

from typing import Optional

# Канонічні значення (як у БД genders.gendername).
FEMALE = "Жіноча"
MALE = "Чоловіча"
UNISEX = "Унісекс"
CANONICAL = (FEMALE, MALE, UNISEX)

# Явні відповідності (нижній регістр). Prefix-фолбек нижче ловить решту закінчень.
_MAP = {
    "жіноча": FEMALE, "жіночий": FEMALE, "жіноче": FEMALE, "жіночі": FEMALE,
    "чоловіча": MALE, "чоловічий": MALE, "чоловіче": MALE, "чоловічі": MALE,
    "унісекс": UNISEX, "унісех": UNISEX,
    "дитяча": UNISEX, "дитячий": UNISEX, "дитяче": UNISEX, "дитячі": UNISEX,
    "підліткова": UNISEX, "підлітковий": UNISEX, "підліткове": UNISEX,
}


def normalize_gender(val: Optional[str]) -> str:
    """Канонічна стать або '' (пропустити). Покриває БУДЬ-ЯКЕ закінчення."""
    if not val:
        return ""
    s = str(val).strip().lower()
    if not s:
        return ""
    if s in _MAP:
        return _MAP[s]
    # Prefix-фолбек — ловить будь-яке закінчення; префікси досить специфічні, щоб
    # не зачепити кольори (жовтий→«жов», чорний→«чор» не матчать «жін»/«чол»).
    if s.startswith("жін"):
        return FEMALE
    if s.startswith("чол"):
        return MALE
    if s.startswith(("уніс", "дит", "діт", "підліт")):
        return UNISEX
    return ""  # незнане (сміття) → пропустити, НЕ плодити нову стать
