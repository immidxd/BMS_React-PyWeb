"""Канонічна «Ширина» (колодка) — літера або літера+число, ніколи не словами.

Ширина взуття замовляється літерою (G, W, D, H) або літерою з половиною
(F 1/2, G 1/2) — саме так її пишуть постачальники. У журналі час від часу
зʼявлялись словесні форми («Стандартна», «Широка»), і вони протікали в базу,
у фільтри й на маркетплейси як окремі значення поряд із літерними.

Тому нормалізація тут, в одному місці, і викликається з ОБОХ боків:
- парсер аркуша (`sheets_parser`) — щоб слово з журналу не осіло в базі;
- API редагування картки — щоб довгий текст не можна було ввести руками.

Контракт `normalize_width` дзеркалить `normalize_condition_name`: не-ширина
повертається як ``None``, а не як виняток, — парсер не має падати через одну
клітинку.
"""

from __future__ import annotations

import re
from typing import Optional


# Значення для випадаючого списку в картці й у формі додавання.
# Порядок — від вужчої до ширшої, як у розмірних таблицях виробників.
CANONICAL_WIDTHS = (
    "D",
    "F",
    "F 1/2",
    "G",
    "G 1/2",
    "H",
    "K",
    "W",
)

# Літерна форма: необовʼязкове число попереду (US 2E/4E), 1–4 літери,
# необовʼязкова половина (F 1/2, G1/2). Довгий текст не проходить за побудовою.
_WIDTH_RE = re.compile(r"^[0-9]{0,2}[A-Za-z]{1,4}(?:\s*[0-9](?:\s*/\s*[0-9])?)?$")


def _key(value: str) -> str:
    return re.sub(r"\s+", " ", value.strip()).casefold()


# Словесні форми з журналу → літера. Розширювати ЛИШЕ за підтвердженою
# відповідністю: «Вузька» свідомо відсутня — у базі її не було, а вгадувати
# літеру за вузькість (D? A?) означало б вигадати дані.
_WIDTH_WORD_ALIASES = {
    "стандартна": "G",
    "стандартний": "G",
    "стандарт": "G",
    "standard": "G",
    "normal": "G",
    "широка": "W",
    "широкий": "W",
    "wide": "W",
}


def normalize_width(value: object) -> Optional[str]:
    """Канонічна ширина або ``None``, якщо це не ширина.

    'Стандартна' → 'G', 'широка' → 'W', 'g 1/2' → 'G 1/2', 'ee' → 'EE'.
    Порожнє, слово поза словником, будь-який довгий текст → ``None``.
    """
    if value is None:
        return None
    raw = str(value).strip()
    if not raw:
        return None

    word = _WIDTH_WORD_ALIASES.get(_key(raw))
    if word:
        return word

    if not _WIDTH_RE.match(raw):
        return None

    # 'g1/2' і 'G 1 / 2' — одне й те саме значення; зводимо до 'G 1/2'.
    compact = re.sub(r"\s+", "", raw).upper()
    m = re.match(r"^([0-9]{0,2}[A-Z]{1,4})([0-9](?:/[0-9])?)?$", compact)
    if not m:
        return None
    letters, half = m.group(1), m.group(2)
    return f"{letters} {half}" if half else letters


def is_width_like(value: object) -> bool:
    """Чи можна прийняти це значення у поле «Ширина» (для валідації вводу).

    Порожнє вважається прийнятним — це очищення поля, а не помилка.
    """
    if value is None:
        return True
    if not str(value).strip():
        return True
    return normalize_width(value) is not None
